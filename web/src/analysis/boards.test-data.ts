// Key geometry of real split keyboards, for the position tests only: the keymap layout of each board's vial.json
// (keyboards/<board>/keymaps/vial in vial-qmk), read with the repo's KLE parser as the server reads it, keeping only
// the keys shown by default (no decals, layout options at their first choice), rounded to 3 decimals. Indexes are as
// in the list. Each key is [x, y, w, h, r, rx, ry]; left out at the end: w and h 1, r, rx and ry 0.
import type { KeyGeometry } from "../api/types";

export type BoardKeys = number[][];

export function boardKeys(keys: BoardKeys): KeyGeometry[] {
  return keys.map(([x, y, w = 1, h = 1, r = 0, rx = 0, ry = 0]) => ({
    x, y, w, h, x2: 0, y2: 0, w2: w, h2: h, r, rx, ry, layoutIndex: -1, layoutOption: -1, decal: false,
  }));
}

